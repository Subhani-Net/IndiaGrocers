import "server-only"
import { cookies as nextCookies } from "next/headers"

export const getAuthHeaders = async (): Promise<
  { authorization: string } | {}
> => {
  try {
    const cookies = await nextCookies()
    const token = cookies.get("_medusa_jwt")?.value

    if (!token) {
      return {}
    }

    return { authorization: `Bearer ${token}` }
  } catch {
    return {}
  }
}

export const getCacheTag = async (tag: string): Promise<string> => {
  try {
    const cookies = await nextCookies()
    const cacheId = cookies.get("_medusa_cache_id")?.value

    if (!cacheId) {
      return ""
    }

    return `${tag}-${cacheId}`
  } catch (error) {
    return ""
  }
}

export const getCacheOptions = async (
  tag: string
): Promise<{ tags: string[]; revalidate?: number } | {}> => {
  if (typeof window !== "undefined") {
    return {}
  }

  const cacheTag = await getCacheTag(tag)

  if (!cacheTag) {
    return {}
  }

  // Cache TTL by data type
  const revalidateMap: Record<string, number> = {
    products: 60,       // Products: 1 min
    categories: 300,    // Categories: 5 min
    collections: 300,   // Collections: 5 min
    regions: 3600,      // Regions: 1 hour
    locales: 3600,      // Locales: 1 hour
    shippingOptions: 120, // Shipping: 2 min
    fulfillment: 120,    // Fulfillment: 2 min
    payment_providers: 600, // Payment: 10 min
    variants: 60,        // Variants: 1 min
    orders: 30,          // Orders: 30 sec
  }

  const revalidate = revalidateMap[tag] ?? 60

  return { tags: [`${cacheTag}`], revalidate }
}

export const setAuthToken = async (token: string) => {
  const cookies = await nextCookies()
  cookies.set("_medusa_jwt", token, {
    maxAge: 60 * 60 * 24 * 7,
    httpOnly: true,
    sameSite: "strict",
    secure: process.env.NODE_ENV === "production",
  })
}

export const removeAuthToken = async () => {
  const cookies = await nextCookies()
  cookies.set("_medusa_jwt", "", {
    maxAge: -1,
  })
}

